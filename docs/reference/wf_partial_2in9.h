/* wf_partial_2in9.h
 *
 * Partial-refresh waveform LUT for a 2.9" 128x296 SSD1680 panel
 * (GoodDisplay GDEY029T94 / GDEM029T94, Waveshare 2.9inch e-Paper Module V2).
 *
 * PRIMARY SOURCE (verbatim, order and values preserved):
 *   https://github.com/waveshareteam/e-Paper/blob/master/RaspberryPi_JetsonNano/c/lib/e-Paper/EPD_2in9_V2.c
 *   raw: https://raw.githubusercontent.com/waveshareteam/e-Paper/master/RaspberryPi_JetsonNano/c/lib/e-Paper/EPD_2in9_V2.c
 *   symbol: UBYTE _WF_PARTIAL_2IN9[159]   (file header says "This version: V1.2, Date: 2023-12-21")
 *
 * BYTE COUNT: the array is declared and populated with exactly 159 bytes.
 *   - Bytes [0..152]  (153 bytes) are the ONLY bytes sent to command 0x32 (Write LUT register).
 *     Waveshare's EPD_2IN9_V2_LUT() loops `for(count=0; count<153; count++)`.
 *   - Bytes [153..158] (6 bytes) are NOT part of the 0x32 payload. They are written to
 *     separate registers by EPD_2IN9_V2_LUT_by_host(), which Waveshare calls ONLY in the
 *     full / fast / 4-gray init paths -- NOT in the partial path:
 *       lut[153] = 0x22 -> command 0x3F  (Option for LUT end / "EOPT")
 *       lut[154] = 0x17 -> command 0x03  (Gate driving voltage, VGH)
 *       lut[155] = 0x41 -> command 0x04  (Source driving voltage, VSH1)
 *       lut[156] = 0xB0 -> command 0x04  (2nd byte, VSH2)
 *       lut[157] = 0x32 -> command 0x04  (3rd byte, VSL)
 *       lut[158] = 0x36 -> command 0x2C  (Write VCOM register)
 *
 * CORROBORATING SOURCES (byte-for-byte identical to the 159 bytes below):
 *   https://raw.githubusercontent.com/waveshareteam/e-Paper/master/Arduino/epd2in9_V2/epd2in9_V2.cpp
 *   https://raw.githubusercontent.com/waveshareteam/e-Paper/master/STM32/STM32-F103ZET6/User/e-Paper/EPD_2in9_V2.c
 *   GxEPD2 GxEPD2_290_T94_V2::lut_partial[] -- identical to bytes [0..152], 153 bytes, no trailing 6:
 *   https://raw.githubusercontent.com/ZinggJM/GxEPD2/master/src/epd/GxEPD2_290_T94_V2.cpp
 *
 * KNOWN DISAGREEMENT (one byte):
 *   Waveshare's Python driver has 0x1 where the C drivers have 0x2 at index 66
 *   (the 7th byte of the Group0 TP/SR/RP row, i.e. the "RP of Group0" repeat count).
 *   https://raw.githubusercontent.com/waveshareteam/e-Paper/master/RaspberryPi_JetsonNano/python/lib/waveshare_epd/epd2in9_V2.py
 *   -> WF_PARTIAL_2IN9 row 6 reads: 0x0A,0x0,0x0,0x0,0x0,0x0,0x1,
 *   The C value (0x2) is used below, since GxEPD2's independently-derived
 *   GoodDisplay-based lut_partial also uses 0x2.
 */

